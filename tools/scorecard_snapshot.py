#!/usr/bin/env python3
"""
File: tools/scorecard_snapshot.py
Description: The fleet's security-posture snapshot (bamr87/bamr87#513). Turns
             OpenSSF Scorecard CLI results (`scorecard --format=json`, one file
             per registry repo, collected read-only by
             .github/workflows/scorecard-sweep.yml) into the `security:` block of
             _data/conformance.yml, which the dash's Projects table shows as its
             `scorecard` column.

             ingest DIR   fold DIR/<registry-name>.json into the raw cache
                          _data/scorecard.yml (details dropped; repos missing
                          from DIR keep their last result)
             (default)    render the block from the raw cache; --write splices
                          it into _data/conformance.yml, --check re-renders and
                          fails (exit 1) when the committed block differs —
                          a hand edit, or a cache nobody re-rendered.

             The block is the LAST top-level key of conformance.yml, so
             `conformance.py fleet --write` (which rewrites the file) carries it
             over byte for byte (`conformance.security_span`).

             Pinned-Dependencies is never recorded: the fleet is always-latest
             by policy (docs/DEPENDENCIES.md), so it would fail every repo by
             design. See docs/SECURITY-POSTURE.md.
Usage: python3 tools/scorecard_snapshot.py targets [REGISTRY]   # the sweep's matrix (JSON)
       python3 tools/scorecard_snapshot.py ingest DIR
       python3 tools/scorecard_snapshot.py [--write | --check]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

from conformance import security_span  # noqa: E402

HUB = Path(__file__).resolve().parent.parent
RAW = HUB / "_data" / "scorecard.yml"
CONFORMANCE = HUB / "_data" / "conformance.yml"

# The checks the sweep runs, in display order. The workflow passes exactly this
# list to `--checks` (test_scorecard_snapshot.py holds the two equal).
CHECKS = (
    "Branch-Protection",
    "Token-Permissions",
    "Dangerous-Workflow",
    "Code-Review",
    "Security-Policy",
    "SAST",
    "Vulnerabilities",
)
EXCLUDED = {
    "Pinned-Dependencies": "always-latest by policy (docs/DEPENDENCIES.md): it would fail every repo by design",
}
RAW_HEADER = (
    "# GENERATED by tools/scorecard_snapshot.py ingest — raw OpenSSF Scorecard results per\n"
    "# registry repo (details dropped), collected read-only by scorecard-sweep.yml. The\n"
    "# `security:` block of _data/conformance.yml is rendered from this; do not hand-edit.\n"
)
BLOCK_COMMENT = (
    "  # GENERATED by tools/scorecard_snapshot.py from _data/scorecard.yml (OpenSSF Scorecard,\n"
    "  # read-only). Scores 0-10; -1 = inconclusive (shown as ?). Do not hand-edit.\n"
)


def trim(raw: dict) -> dict:
    """The parts of one Scorecard result the snapshot uses — no details, no docs."""
    return {
        "date": raw.get("date"),
        "repo": {"name": (raw.get("repo") or {}).get("name"), "commit": (raw.get("repo") or {}).get("commit")},
        "scorecard": {"version": (raw.get("scorecard") or {}).get("version")},
        "score": raw.get("score"),
        "checks": [
            {"name": c.get("name"), "score": c.get("score"), "reason": c.get("reason")}
            for c in raw.get("checks") or []
            if isinstance(c, dict)
        ],
    }


def _score(v) -> float | int:
    """Scorecard's -1 (inconclusive) and anything unreadable both become -1."""
    if isinstance(v, bool) or not isinstance(v, (int, float)) or v < 0:
        return -1
    return int(v) if float(v).is_integer() else round(float(v), 1)


def normalize(results: dict) -> dict:
    """{repo: {date, commit, checks: {name: score|-1}, aggregate}} in registry-name order."""
    repos = {}
    for name in sorted(results, key=str.lower):
        r = results[name] or {}
        by_name = {c.get("name"): c.get("score") for c in r.get("checks") or [] if isinstance(c, dict)}
        repos[name] = {
            "date": str(r.get("date") or "")[:10],
            "commit": str((r.get("repo") or {}).get("commit") or "")[:12],
            "checks": {chk: _score(by_name.get(chk)) for chk in CHECKS},
            "aggregate": _score(r.get("score")),
        }
    return repos


def render_block(cache: dict) -> str:
    """The `security:` block as text — top-level key, comment, then the body."""
    results = (cache or {}).get("results") or {}
    body = {
        "source": "ossf/scorecard",
        "generated_at": (cache or {}).get("generated_at"),
        "checks": list(CHECKS),
        "excluded": dict(EXCLUDED),
        "repos": normalize(results),
    }
    dumped = yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=120)
    return "security:\n" + BLOCK_COMMENT + "".join("  " + ln if ln.strip() else ln for ln in dumped.splitlines(True))


def splice(text: str, block: str) -> str:
    """conformance.yml text with its `security:` block replaced by (or ending in) `block`."""
    start, _ = security_span(text)
    head = text if start is None else text[:start]
    if head and not head.endswith("\n"):
        head += "\n"
    return head + block


def load_cache(path: Path) -> dict | None:
    if not path.is_file():
        return None
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    return data if isinstance(data, dict) else None


def ingest(src: Path, raw_path: Path, now: str) -> int:
    cache = load_cache(raw_path) or {}
    results = dict(cache.get("results") or {})
    n = 0
    for f in sorted(src.glob("*.json")):
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print(f"skip {f.name}: {exc}", file=sys.stderr)
            continue
        if not isinstance(data, dict) or not data.get("checks"):
            print(f"skip {f.name}: not a Scorecard result", file=sys.stderr)
            continue
        results[f.stem] = trim(data)
        n += 1
    out = {"generated_at": now, "results": {k: results[k] for k in sorted(results, key=str.lower)}}
    raw_path.write_text(RAW_HEADER + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120),
                        encoding="utf-8")
    print(f"ingested {n} result(s) into {raw_path} ({len(results)} repo(s) cached)")
    return 0


def check(raw_path: Path, conf_path: Path) -> int:
    text = conf_path.read_text(encoding="utf-8") if conf_path.is_file() else ""
    start, end = security_span(text)
    committed = None if start is None else text[start:end]
    cache = load_cache(raw_path)
    if cache is None:
        if committed is None:
            print("ok: no Scorecard sweep recorded yet (no _data/scorecard.yml, no security: block)")
            return 0
        print(f"FAIL: {conf_path.name} has a security: block but {raw_path.name} is missing — it was hand-edited")
        return 1
    if committed != render_block(cache):
        print(f"FAIL: the security: block in {conf_path.name} does not match {raw_path.name} "
              f"(hand-edited, or not re-rendered) — run `python3 tools/scorecard_snapshot.py --write`")
        return 1
    print(f"ok: security: block matches {raw_path.name} ({len(cache.get('results') or {})} repo(s))")
    return 0


def write(raw_path: Path, conf_path: Path) -> int:
    cache = load_cache(raw_path)
    if cache is None:
        print(f"nothing to write: {raw_path} is missing (run `ingest` first)", file=sys.stderr)
        return 1
    text = conf_path.read_text(encoding="utf-8") if conf_path.is_file() else ""
    conf_path.write_text(splice(text, render_block(cache)), encoding="utf-8")
    print(f"wrote the security: block into {conf_path}")
    return 0


def targets(registry_path: Path) -> list[dict]:
    """Registry repos on github.com, archived ones skipped, as [{name, nwo}] — the sweep's matrix.

    Visibility is not in the registry: the workflow drops private repos when the
    job token cannot see them (the sweep is public-repos-only and read-only).
    """
    reg = yaml.safe_load(registry_path.read_text(encoding="utf-8")) or []
    out, seen = [], set()
    for e in reg:
        if not isinstance(e, dict) or str(e.get("status", "")).lower() == "archived":
            continue
        m = re.match(r"^https://github\.com/([^/\s]+/[^/\s]+?)(?:\.git)?/?$", str(e.get("repo_url") or ""))
        if not m or m.group(1).lower() in seen:
            continue
        seen.add(m.group(1).lower())
        out.append({"name": str(e["name"]), "nwo": m.group(1)})
    return out


def main(argv: list[str] | None = None) -> int:
    import datetime as dt

    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", nargs="?", choices=["ingest", "render", "targets"], default="render")
    ap.add_argument("src", nargs="?", help="ingest: directory of <registry-name>.json Scorecard results")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="splice the block into conformance.yml")
    mode.add_argument("--check", action="store_true", help="exit 1 when the committed block is not the rendering")
    ap.add_argument("--raw", default=str(RAW))
    ap.add_argument("--conformance", default=str(CONFORMANCE))
    a = ap.parse_args(argv)
    raw_path, conf_path = Path(a.raw), Path(a.conformance)
    if a.cmd == "targets":
        print(json.dumps(targets(Path(a.src) if a.src else HUB / "_data" / "projects.yml")))
        return 0
    if a.cmd == "ingest":
        if not a.src:
            ap.error("ingest needs a directory")
        now = dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
        return ingest(Path(a.src), raw_path, now)
    if a.check:
        return check(raw_path, conf_path)
    if a.write:
        return write(raw_path, conf_path)
    cache = load_cache(raw_path)
    print(render_block(cache) if cache else "no Scorecard results cached yet", end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
