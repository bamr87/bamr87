def cmd_check(reg, args):
    problems = validate(reg)
    for p in problems:
        print(f"  ✗ {p}")

    stale, unchecked = [], []
    for pname, pspec in (reg.get("projects") or {}).items():
        pspec = pspec or {}
        if pspec.get("host") != "compose":
            continue
        if not submodule_present(pspec):
            # Cannot regenerate what is not on disk, so staleness is unknowable
            # here. This is the NORMAL case in CI.
            unchecked.append(pname)
            continue
        want = gen_override(reg, pname, pspec)
        path = os.path.join(OVERRIDE_DIR, f"{pname}.yml")
        have = open(path).read() if os.path.exists(path) else None
        if want is None and have is None:
            continue
        if want != have:
            stale.append(pname)
    if stale:
        problems.append(f"stale overrides: {', '.join(stale)}")
        print(f"  ✗ stale compose/overrides: {', '.join(stale)}"
              f" — run tools/fleet-compose.py sync")
    if unchecked:
        print(f"  ! {len(unchecked)} override(s) not verified "
              f"(submodule not checked out) — normal in CI")

    hub_ov = os.path.join(OVERRIDE_DIR, "hub.yml")
    if os.path.exists(hub_ov) and open(hub_ov).read() != gen_hub_override(reg):
        problems.append("stale compose/overrides/hub.yml")
        print("  ✗ compose/overrides/hub.yml is stale — run tools/fleet-compose.py sync")

    if os.path.exists(INCLUDE_FILE) and open(INCLUDE_FILE).read() != gen_include(reg):
        problems.append("stale compose.fleet.yml")
        print("  ✗ compose.fleet.yml is stale — run tools/fleet-compose.py sync")

    if args.audit:
        for f in audit_submodule_ports(reg):
            print(f"  ! {f}")

    if not problems:
        total = sum(len((p or {}).get("services") or {})
                    for p in (reg.get("projects") or {}).values())
        print(f"  ✓ {total} allocations across "
              f"{len(reg.get('projects') or {})} projects — no collisions, all in band")
    return 1 if problems else 0


def cmd_sync(reg, args):
    os.makedirs(OVERRIDE_DIR, exist_ok=True)
    written, skipped = [], []

    with open(ENV_FILE, "w") as fh:
        fh.write(gen_env(reg))
    written.append(".env.fleet")

    for pname, pspec in (reg.get("projects") or {}).items():
        pspec = pspec or {}
        if pspec.get("host") != "compose":
            continue
        path = os.path.join(OVERRIDE_DIR, f"{pname}.yml")
        if not submodule_present(pspec):
            # NEVER delete a committed override just because the submodule is not
            # checked out — `sync` on a fresh clone would wipe all of them.
            if os.path.exists(path):
                skipped.append(pname)
            continue
        text = gen_override(reg, pname, pspec)
        if text is None:
            if os.path.exists(path):
                os.remove(path)
                written.append(f"compose/overrides/{pname}.yml (removed)")
            continue
        with open(path, "w") as fh:
            fh.write(text)
        written.append(f"compose/overrides/{pname}.yml")

    with open(os.path.join(OVERRIDE_DIR, "hub.yml"), "w") as fh:
        fh.write(gen_hub_override(reg))
    written.append("compose/overrides/hub.yml")

    with open(INCLUDE_FILE, "w") as fh:
        fh.write(gen_include(reg))
    written.append("compose.fleet.yml")

    for w in written:
        print(f"  wrote {w}")
    if skipped:
        print(f"  kept {len(skipped)} override(s) untouched "
              f"(submodule not checked out): {', '.join(skipped)}")
    return 0


def cmd_env(reg, args):
    with open(ENV_FILE, "w") as fh:
        fh.write(gen_env(reg))
    print(f"  wrote .env.fleet")
    return 0


def cmd_show(reg, args):
    projects = reg.get("projects") or {}
    if args.project:
        projects = {k: v for k, v in projects.items() if k == args.project}
        if not projects:
            print(f"no such project: {args.project}")
            return 1

    print(f"{'PROJECT':24} {'SERVICE':18} {'PORT':>6}  {'BAND':10} HOST")
    print("-" * 78)
    for name, spec in (reg.get("shared") or {}).items():
        for label, port in (spec.get("ports") or {}).items():
            flag = "shared" if spec.get("default") else "shared(opt-in)"
            print(f"{'(shared)':24} {name + '.' + label:18} {port:>6}  {'-':10} {flag}")
    print("-" * 78)
    for pname, pspec in projects.items():
        pspec = pspec or {}
        host = pspec.get("host", "?")
        rows = list((pspec.get("services") or {}).items())
        rows += [(f"{k} (debug)", v) for k, v in (pspec.get("debug") or {}).items()]
        for sname, alloc in rows:
            alloc = alloc or {}
            lr = f"  +lr {alloc['livereload']}" if alloc.get("livereload") else ""
            print(f"{pname:24} {sname:18} {alloc.get('port', '?'):>6}  "
                  f"{alloc.get('band', '-'):10} {host}{lr}")
    return 0


def main():
    ap = argparse.ArgumentParser(description="Project _data/ports.yml onto the fleet dev stack")
    sub = ap.add_subparsers(dest="cmd")

    c = sub.add_parser("check", help="gate the allocation and the generated files")
    c.add_argument("--audit", action="store_true",
                   help="also report submodules still publishing hardcoded ports")
    sub.add_parser("sync", help="regenerate .env.fleet, overrides and compose.fleet.yml")
    sub.add_parser("env", help="regenerate .env.fleet only")
    s = sub.add_parser("show", help="print the allocation table")
    s.add_argument("project", nargs="?")

    args = ap.parse_args()
    if not args.cmd:
        ap.print_help()
        return 0

    reg = load_registry()
    return {"check": cmd_check, "sync": cmd_sync,
            "env": cmd_env, "show": cmd_show}[args.cmd](reg, args)


