# Validation
# ---------------------------------------------------------------------------
def validate(reg):
    """Return a list of problem strings. Empty list == the allocation is sound."""
    problems = []
    bands = reg.get("bands") or {}
    shared = reg.get("shared") or {}
    projects = reg.get("projects") or {}

    seen = {}   # port -> "project/service"

    def claim(port, who):
        if port in seen:
            problems.append(f"port {port} claimed twice: {seen[port]} and {who}")
        else:
            seen[port] = who

    # Shared services own their ports before anyone else.
    for name, spec in shared.items():
        for label, port in (spec.get("ports") or {}).items():
            claim(int(port), f"shared/{name}.{label}")

    for pname, pspec in projects.items():
        pspec = pspec or {}
        allocs = list((pspec.get("services") or {}).items())
        allocs += list((pspec.get("debug") or {}).items())

        for sname, alloc in allocs:
            alloc = alloc or {}
            port = alloc.get("port")
            band = alloc.get("band")
            if port is None:
                problems.append(f"{pname}/{sname}: no port")
                continue
            claim(int(port), f"{pname}/{sname}")

            # Band conformance — the point of having bands at all.
            if band not in bands:
                problems.append(f"{pname}/{sname}: unknown band '{band}'")
            else:
                lo, hi = bands[band]["range"]
                if not (lo <= int(port) <= hi):
                    problems.append(
                        f"{pname}/{sname}: port {port} outside band '{band}' [{lo}-{hi}]")

            if not alloc.get("var"):
                problems.append(f"{pname}/{sname}: no env var name")

            lr = alloc.get("livereload")
            if lr is not None:
                claim(int(lr), f"{pname}/{sname}.livereload")
                lo, hi = bands["livereload"]["range"]
                if not (lo <= int(lr) <= hi):
                    problems.append(
                        f"{pname}/{sname}: livereload {lr} outside band [{lo}-{hi}]")

        # `unique:` ports are declared-as-is; still claim them so a future
        # allocation cannot land on top of neo4j or ollama.
        for sname, ports in (pspec.get("unique") or {}).items():
            for port in ports:
                claim(int(port), f"{pname}/{sname} (unique)")

        # The compose file the allocation talks about must exist and must
        # actually define the services named.
        if pspec.get("host") == "compose":
            rel = pspec.get("compose")
            if not rel:
                problems.append(f"{pname}: host=compose but no `compose:` path")
                continue
            doc = load_compose(rel)
            if doc is None:
                continue  # submodule not checked out; not this gate's business
            defined = set((doc.get("services") or {}).keys())
            for sname, _ in allocs:
                if sname not in defined:
                    problems.append(
                        f"{pname}: '{sname}' allocated but not a service in {rel}"
                        f" (has: {', '.join(sorted(defined)) or 'none'})")

    return problems


def audit_submodule_ports(reg):
    """Report submodule compose files still publishing a hardcoded, contended
    port. Advisory: the hub override neutralizes it for the fleet stack, but it
    still collides for anyone running that repo standalone alongside another."""
    findings = []
    projects = reg.get("projects") or {}
    for pname, pspec in projects.items():
        pspec = pspec or {}
        if pspec.get("host") != "compose":
            continue
        doc = load_compose(pspec.get("compose") or "")
        if doc is None:
            continue
        for sname, svc in (doc.get("services") or {}).items():
            svc = svc or {}
            if svc.get("container_name"):
                findings.append(
                    f"{pname}/{sname}: sets container_name "
                    f"'{svc['container_name']}' (global to the daemon)")
            for entry in svc.get("ports") or []:
                published, target, _ = parse_port(entry)
                if published and "$" not in str(published):
                    findings.append(
                        f"{pname}/{sname}: hardcoded published port {published}"
                        f"->{target} (not env-overridable)")
    return findings


