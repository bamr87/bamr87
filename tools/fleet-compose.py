#!/usr/bin/env python3
# ============================================================================
# File:          tools/fleet-compose.py
# Description:   Projects _data/ports.yml onto the fleet dev stack — generates
#                .env.fleet, the hub-owned compose/overrides/*.yml, and
#                compose.fleet.yml, and validates the whole allocation.
# Author:        bamr87
# Created:       2026-09-20
# Last Modified: 2026-09-20
# Version:       1.0.0
# Usage:
#   tools/fleet-compose.py check          # gate: bands, collisions, override staleness
#   tools/fleet-compose.py sync           # (re)generate .env.fleet + overrides + include
#   tools/fleet-compose.py env            # write .env.fleet only
#   tools/fleet-compose.py show [project] # print the allocation table
# ============================================================================
#
# WHY THIS EXISTS
#
# The submodules are separate repos; the hub cannot commit to them. But Compose
# `include:` accepts a LIST of paths — the first is the base, the rest are
# overrides — and resolves every relative path (build contexts above all)
# against the BASE file's directory. So the hub can remap a submodule's ports,
# container_name and networks from a file it owns, with the submodule's own
# docker-compose.yml untouched and still standalone-runnable.
#
# That is the whole trick. The generated overrides are a hub-side projection of
# _data/ports.yml, never hand-edited; when a submodule later adopts the
# parameterized form upstream, its override shrinks to nothing and is dropped.

import json
import os
import re
import sys
import argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
# One port parser for the whole toolchain: the harmonizer that rewrites the
# submodules and this generator that overrides them must agree byte-for-byte on
# what `${BIND_HOST:-127.0.0.1}:${PORT:-5433}:5432` means.
from docker_harmonize import parse_port, rewrite_host_port_refs  # noqa: E402

try:
    import yaml
except ImportError:  # pragma: no cover - environment problem, not a code path
    sys.stderr.write(
        "fleet-compose: PyYAML is required (pip install pyyaml, or run inside devenv)\n")
    raise SystemExit(2)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORTS_YML = os.path.join(ROOT, "_data", "ports.yml")
OVERRIDE_DIR = os.path.join(ROOT, "compose", "overrides")
ENV_FILE = os.path.join(ROOT, ".env.fleet")
INCLUDE_FILE = os.path.join(ROOT, "compose.fleet.yml")

GENERATED = "# GENERATED by tools/fleet-compose.py from _data/ports.yml — do not hand-edit."

# Services the shared stack replaces: service name -> shared key in ports.yml.
# Only entries whose shared service is `default: true` are actually profiled
# out; the rest are merely deconflicted.
REPLACED_BY_SHARED = {"phoenix": "phoenix"}


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------
def load_registry():
    with open(PORTS_YML) as fh:
        return yaml.safe_load(fh) or {}


def submodule_present(pspec):
    """Is this project's compose file actually on disk?

    `gen_override()` returns None for BOTH "no override needed" and "submodule
    not checked out", and conflating the two was doubly wrong: CI checks out
    WITHOUT submodules, so every override read as stale and check (m) failed
    every PR — and `sync` in that state DELETED the 15 committed override files.
    """
    rel = (pspec or {}).get("compose")
    return bool(rel) and os.path.exists(os.path.join(ROOT, rel))


def load_compose(path):
    """Parse a submodule compose file. Missing is not fatal: a submodule can be
    un-checked-out, and the gate must still run in CI."""
    full = os.path.join(ROOT, path)
    if not os.path.exists(full):
        return None
    with open(full) as fh:
        try:
            return yaml.safe_load(fh) or {}
        except yaml.YAMLError as exc:
            raise SystemExit(f"fleet-compose: cannot parse {path}: {exc}")


