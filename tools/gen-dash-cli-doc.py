#!/usr/bin/env python3
"""
File: tools/gen-dash-cli-doc.py
Description: Generate the dash CLI reference — the AUTO:dash-cli span in
             docs/DASH.md — from `tools/dash help`, the one place the
             commands are defined. The span used to be a hand-copied list
             that had fallen a dozen commands behind the CLI (specs/DOCS.md
             UPS-DOC-05: reference derivable from source is generated).
Author: bamr87
Created: 2026-10-22
Last Modified: 2026-10-22
Version: 0.1.0
Usage: python3 tools/gen-dash-cli-doc.py [--check]
       --check  exit 1 when the span in docs/DASH.md is stale
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "DASH.md"
START = "<!-- AUTO:dash-cli:start -->"
END = "<!-- AUTO:dash-cli:end -->"
NOTE = "<!-- GENERATED by tools/gen-dash-cli-doc.py from `tools/dash help` — do not edit by hand -->"
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def help_text() -> str:
    return subprocess.run(["bash", str(ROOT / "tools" / "dash"), "help"], capture_output=True,
                          text=True, check=True, cwd=ROOT).stdout


def entries(raw: str) -> list[tuple[str, str]]:
    """(command, description) pairs. The help prints each command in bold, so
    the escape codes delimit it exactly; indented lines continue an entry."""
    rows: list[tuple[str, str]] = []
    for line in raw.splitlines()[1:]:
        m = re.match(r"^  \x1b\[1m(dash .+?)\x1b\[0m\s*(.*)$", line)
        if m:
            rows.append((m.group(1).strip(), ANSI.sub("", m.group(2)).strip()))
        elif rows and line.startswith("    ") and line.strip():
            cmd, desc = rows[-1]
            rows[-1] = (cmd, f"{desc} {ANSI.sub('', line).strip()}".strip())
    return rows


def render(rows: list[tuple[str, str]]) -> str:
    lines = [START, NOTE, "", "| Command | What it does |", "| --- | --- |"]
    for cmd, desc in rows:
        esc = chr(92) + "|"  # a pipe splits a GFM table cell even inside a code span
        lines.append(f"| `tools/{cmd.replace('|', esc)}` | {desc.replace('|', esc)} |")
    lines.append(END)
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    doc = DOC.read_text(encoding="utf-8")
    start, end = doc.find(START), doc.find(END)
    if start < 0 or end < 0:
        print(f"{DOC.relative_to(ROOT)} has no {START} … {END} span", file=sys.stderr)
        return 1
    fresh = doc[:start] + render(entries(help_text())) + doc[end + len(END):]
    if fresh == doc:
        return 0
    if check:
        print(f"{DOC.relative_to(ROOT)} dash CLI reference is stale (run: python3 tools/gen-dash-cli-doc.py)",
              file=sys.stderr)
        return 1
    DOC.write_text(fresh, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
