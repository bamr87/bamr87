#!/usr/bin/env python3
"""
Offline fixture tests for tools/scorecard_snapshot.py (bamr87/bamr87#513): the
OpenSSF Scorecard results → `security:` block of _data/conformance.yml, its
--check gate, `conformance.py fleet --write` preserving the block byte for
byte, and the read-only shape of .github/workflows/scorecard-sweep.yml.

No network, no Docker, no pytest. Needs PyYAML:

    python3 tools/test_scorecard_snapshot.py
"""
from __future__ import annotations

import contextlib
import io
import json
import re
import shutil
import sys
import tempfile
import unittest
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import conformance  # noqa: E402
import scorecard_snapshot as sc  # noqa: E402

HUB = Path(__file__).resolve().parent.parent
WORKFLOW = HUB / ".github" / "workflows" / "scorecard-sweep.yml"


def scorecard_json(nwo: str, scores: dict[str, int], aggregate: float) -> dict:
    """A result in the shape `scorecard --format=json` prints (v5)."""
    return {
        "date": "2026-11-02T06:47:11Z",
        "repo": {"name": f"github.com/{nwo}", "commit": "0123456789abcdef0123456789abcdef01234567"},
        "scorecard": {"version": "v5.3.0", "commit": "feedface"},
        "score": aggregate,
        "checks": [
            {"details": ["Warn: something"], "score": s, "reason": f"{n} reason", "name": n,
             "documentation": {"url": "https://example.invalid", "short": "doc"}}
            for n, s in scores.items()
        ],
        "metadata": None,
    }


FIXTURES = {
    "zer0-mistakes": scorecard_json("bamr87/zer0-mistakes", {
        "Branch-Protection": -1, "Token-Permissions": 0, "Dangerous-Workflow": 10, "Code-Review": 3,
        "Security-Policy": 10, "SAST": 7, "Vulnerabilities": 9}, 5.6),
    "fredgar-ai": scorecard_json("bamr87/fredgar-ai", {
        "Branch-Protection": 3, "Token-Permissions": 10, "Dangerous-Workflow": 10, "Code-Review": 0,
        "Security-Policy": 0, "SAST": 0, "Vulnerabilities": 10}, 4.7),
}
CONFORMANCE = (
    "# GENERATED by tools/conformance.py fleet\n"
    "generated_at: '2026-10-20T20:10:25Z'\n"
    "summary:\n  repos: 2\n"
    "repos:\n- name: fredgar-ai\n  must_failed: 1\n"
)


class Sandbox(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp(prefix="scorecard-test-"))
        self.raw = self.tmp / "scorecard.yml"
        self.conf = self.tmp / "conformance.yml"
        self.conf.write_text(CONFORMANCE, encoding="utf-8")
        self.src = self.tmp / "results"
        self.src.mkdir()
        for name, data in FIXTURES.items():
            (self.src / f"{name}.json").write_text(json.dumps(data), encoding="utf-8")

    def tearDown(self) -> None:
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_main(self, *args: str) -> int:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            return sc.main([*args, "--raw", str(self.raw), "--conformance", str(self.conf)])

    def sweep(self) -> None:
        self.assertEqual(self.run_main("ingest", str(self.src)), 0)
        self.assertEqual(self.run_main("--write"), 0)


class SnapshotTests(Sandbox):
    def test_normalized_shape(self) -> None:
        self.sweep()
        sec = yaml.safe_load(self.conf.read_text(encoding="utf-8"))["security"]
        self.assertEqual(list(sec["repos"]), ["fredgar-ai", "zer0-mistakes"])
        z = sec["repos"]["zer0-mistakes"]
        self.assertEqual(set(z), {"date", "commit", "checks", "aggregate"})
        self.assertEqual(z["date"], "2026-11-02")
        self.assertEqual(z["checks"]["Branch-Protection"], -1, "inconclusive stays -1, never a failure score")
        self.assertEqual(z["aggregate"], 5.6)
        self.assertEqual(list(z["checks"]), list(sc.CHECKS))
        self.assertNotIn("Pinned-Dependencies", sec["checks"])
        self.assertIn("Pinned-Dependencies", sec["excluded"])

    def test_raw_cache_drops_details(self) -> None:
        self.sweep()
        raw = self.raw.read_text(encoding="utf-8")
        self.assertNotIn("Warn: something", raw)
        self.assertNotIn("documentation", raw)

    def test_rest_of_conformance_untouched(self) -> None:
        self.sweep()
        text = self.conf.read_text(encoding="utf-8")
        self.assertTrue(text.startswith(CONFORMANCE))
        self.assertEqual(yaml.safe_load(text)["repos"], [{"name": "fredgar-ai", "must_failed": 1}])

    def test_write_is_idempotent(self) -> None:
        self.sweep()
        first = self.conf.read_text(encoding="utf-8")
        self.assertEqual(self.run_main("--write"), 0)
        self.assertEqual(self.conf.read_text(encoding="utf-8"), first)

    def test_check_passes_on_fresh_snapshot(self) -> None:
        self.sweep()
        self.assertEqual(self.run_main("--check"), 0)

    def test_check_fails_after_hand_edit(self) -> None:
        self.sweep()
        text = self.conf.read_text(encoding="utf-8")
        edited = re.sub(r"(Code-Review: )3", r"\g<1>10", text, count=1)
        self.assertNotEqual(edited, text)
        self.conf.write_text(edited, encoding="utf-8")
        self.assertEqual(self.run_main("--check"), 1)

    def test_check_fails_on_block_without_cache(self) -> None:
        self.conf.write_text(CONFORMANCE + "security:\n  repos: {}\n", encoding="utf-8")
        self.assertEqual(self.run_main("--check"), 1)

    def test_check_passes_before_first_sweep(self) -> None:
        self.assertEqual(self.run_main("--check"), 0)

    def test_ingest_keeps_repos_missing_from_this_run(self) -> None:
        self.sweep()
        (self.src / "fredgar-ai.json").unlink()
        (self.src / "zer0-mistakes.json").write_text("not json", encoding="utf-8")
        self.assertEqual(self.run_main("ingest", str(self.src)), 0)
        cached = yaml.safe_load(self.raw.read_text(encoding="utf-8"))["results"]
        self.assertEqual(set(cached), {"fredgar-ai", "zer0-mistakes"})


class PreservationTests(Sandbox):
    """`tools/dash spec fleet --write` rewrites conformance.yml: the block must survive byte for byte."""

    def fleet_write(self) -> None:
        hub = self.tmp / "hub"
        (hub / "_data").mkdir(parents=True)
        for f in ("specs.yml", "standards.yml"):
            shutil.copy(HUB / "_data" / f, hub / "_data" / f)
        (hub / "_data" / "projects.yml").write_text("[]\n", encoding="utf-8")
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(conformance.main(["fleet", "--hub", str(hub), "--write", str(self.conf)]), 0)

    def test_fleet_write_keeps_security_block_byte_identical(self) -> None:
        self.sweep()
        text = self.conf.read_text(encoding="utf-8")
        start, end = conformance.security_span(text)
        block = text[start:end]
        self.fleet_write()
        after = self.conf.read_text(encoding="utf-8")
        a_start, a_end = conformance.security_span(after)
        self.assertIsNotNone(a_start, "conformance.py fleet --write dropped the security: block")
        self.assertEqual(after[a_start:a_end], block)
        self.assertEqual(self.run_main("--check"), 0)
        self.assertEqual(yaml.safe_load(after)["summary"]["repos"], 0, "the rest was regenerated")

    def test_fleet_write_without_block_adds_none(self) -> None:
        self.fleet_write()
        self.assertNotIn("\nsecurity:", self.conf.read_text(encoding="utf-8"))

    def test_span_stops_at_next_top_level_key(self) -> None:
        text = "a: 1\nsecurity:\n  # c\n  repos: {}\n\nz: 2\n"
        start, end = conformance.security_span(text)
        self.assertEqual(text[start:end], "security:\n  # c\n  repos: {}\n\n")


class WorkflowTests(unittest.TestCase):
    """The sweep is read-only, switchable, scheduled from fleet.yml and publishes via publish-data."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.text = WORKFLOW.read_text(encoding="utf-8")
        cls.wf = yaml.safe_load(cls.text)
        cls.fleet = yaml.safe_load((HUB / "_data" / "fleet.yml").read_text(encoding="utf-8"))

    def test_checks_flag_matches_generator_and_excludes_pinned(self) -> None:
        m = re.search(r"--checks=([A-Za-z,-]+)", self.text)
        self.assertIsNotNone(m, "scorecard is not run with --checks")
        self.assertEqual(tuple(m.group(1).split(",")), sc.CHECKS)
        self.assertNotIn("Pinned-Dependencies", m.group(1))

    def test_read_only(self) -> None:
        self.assertEqual(self.wf["permissions"], {"contents": "read"})
        self.assertNotIn("issues: write", self.text)
        self.assertNotIn("gh issue create", self.text)

    def test_kill_switch_defaults_off(self) -> None:
        self.assertIn("vars.SCORECARD_SWEEP_ENABLED == 'true'", self.text)

    def test_cron_declared_in_fleet_yml(self) -> None:
        cron = self.wf[True]["schedule"][0]["cron"]
        self.assertEqual(cron, self.fleet["schedule"]["scorecard_sweep"])
        self.assertNotEqual(cron.split()[0], "0", "no hub cron fires on the hour")

    def test_publishes_through_publish_data_without_auto_merge(self) -> None:
        steps = [s for job in self.wf["jobs"].values() for s in job.get("steps", [])]
        pub = [s for s in steps if str(s.get("uses", "")).endswith("utilities/publish-data")]
        self.assertEqual(len(pub), 1)
        self.assertEqual(str(pub[0]["with"]["auto-merge"]).lower(), "false")
        self.assertNotRegex(self.text, r"(?m)^\s*git push")


if __name__ == "__main__":
    unittest.main(verbosity=1)
