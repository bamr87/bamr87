#!/usr/bin/env python3
"""
File: tools/jev/generated.py
Description: Main-only generated files — the PR-side guard and the post-merge
             regeneration. GitHub's mergeability check ignores custom merge
             drivers, so `merge=jev-regen` cannot stop two pull requests from
             conflicting on a generated file. The only fix is that pull
             requests stop writing them: a file marked `jev-main-only` in
             .gitattributes is regenerated and committed ONLY by the
             post-merge job on main (.github/workflows/jev-number.yml), and PR
             CI fails a pull request that edits one. Hand-written files with a
             generated SPAN (README AUTO:projects, the PRD feature block, the
             dash CLI reference in docs/DASH.md) are regenerated by the same
             job; on a pull request their drift checks are advisory.
             Doc: docs/JEV.md "Main-only generated files".
Author: bamr87
Created: 2026-10-29
Version: 0.1.0
Usage:
  python3 -m tools.jev generated list                       # the main-only files and the spans
  python3 -m tools.jev generated guard --base origin/main   # fail if this branch edits one
  python3 -m tools.jev generated guard --range A B --head-ref <branch>
  python3 -m tools.jev generated regen                      # regenerate everything (main only)
Exit: 0 clean, 1 a pull request edits a main-only file, 2 usage.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

from .common import git, run

#: The `.gitattributes` attribute that marks a file main-only.
ATTRIBUTE = "jev-main-only"

#: Head branches allowed to write main-only files: the post-merge job's own
#: publish branch (publish-data falls back to a pull request from it).
EXEMPT_HEAD_PREFIXES = ("chore/jev-",)

#: Fallback when a repo carries no .gitattributes declaration.
DEFAULT_MAIN_ONLY = ("CATALOG.md", "docs/README.md")

#: (generator that must exist, argv, what it writes). The post-merge job runs
#: these in order; `files` are the main-only outputs and `spans` the
#: hand-written files whose generated span it rewrites.
REGENERATORS: tuple[tuple[str, list[str], str], ...] = (
    ("tools/governance_lint.py", ["python3", "tools/governance_lint.py", "prd-sync", ".", "--write"],
     "PRD.md feature block (span)"),
    ("tools/gen-dash-cli-doc.py", ["python3", "tools/gen-dash-cli-doc.py"],
     "docs/DASH.md dash CLI reference (span)"),
    ("tools/dash-gen", ["tools/dash-gen", "readme"], "README.md AUTO:projects (span)"),
    ("tools/docs_index.py", ["python3", "tools/docs_index.py", "--write"], "docs/README.md (main-only)"),
    ("tools/gen-catalog.py", ["python3", "tools/gen-catalog.py"], "CATALOG.md (main-only)"),
)

#: The span-bearing files, for the docs and `list`.
SPANS = ("README.md", "PRD.md", "docs/DASH.md")

FIX = ("Pull requests do not edit generated files any more: they are regenerated and "
       "committed on main by the post-merge job (.github/workflows/jev-number.yml, "
       "`chore(jev): assign ids and compile pending fragments`), so two PRs can never "
       "conflict on them. Drop the change from this branch:\n"
       "    git checkout origin/main -- {files}\n"
       "    git commit -m 'chore: leave generated files to main'\n"
       "Edit the SOURCE instead (the tool, spec, doc or data file the generator reads). "
       "Doc: docs/JEV.md, \"Main-only generated files\".")


def main_only_files(repo: Path, candidates: list[str] | None = None) -> list[str]:
    """Paths `.gitattributes` marks `jev-main-only` (among `candidates`, or all tracked)."""
    paths = candidates
    if paths is None:
        paths = git(["ls-files"], cwd=repo).out.split()
    if not paths:
        return []
    res = git(["check-attr", ATTRIBUTE, "--", *paths], cwd=repo)
    out = []
    for line in res.out.splitlines():
        parts = line.rsplit(": ", 2)
        if len(parts) == 3 and parts[2] in ("set", "true"):
            out.append(parts[0])
    if not res.ok:
        out = [p for p in paths if p in DEFAULT_MAIN_ONLY]
    return out


def changed_files(repo: Path, *, base: str = "", rng: tuple[str, str] | None = None) -> list[str]:
    if rng:
        res = git(["diff", "--name-only", rng[0], rng[1]], cwd=repo)
    else:
        res = git(["diff", "--name-only", f"{base}...HEAD"], cwd=repo)
    if not res.ok:
        raise SystemExit(f"jev generated: git diff failed: {res.err.strip()}")
    return [p for p in res.out.splitlines() if p.strip()]


def exempt(head_ref: str) -> bool:
    return any(head_ref.startswith(p) for p in EXEMPT_HEAD_PREFIXES)


def guard(repo: Path, changed: list[str], head_ref: str = "") -> tuple[bool, list[str]]:
    """(ok, offending paths). A post-merge publish branch may write them."""
    if exempt(head_ref):
        return True, []
    bad = main_only_files(repo, changed)
    return not bad, bad


def regen(repo: Path) -> int:
    failed = 0
    for marker, argv, what in REGENERATORS:
        if not (repo / marker).is_file():
            continue
        res = run(argv, cwd=repo, timeout=900)
        print(f"{'ok ' if res.ok else 'ERR'} {what}: {' '.join(argv)}")
        if not res.ok:
            failed += 1
            print((res.err or res.out).strip()[-800:], file=sys.stderr)
    return 1 if failed else 0


def add_arguments(ap: argparse.ArgumentParser) -> None:
    ap.add_argument("action", choices=("list", "guard", "regen"))
    ap.add_argument("--repo", default=".")
    ap.add_argument("--base", default="origin/main", help="guard: compare BASE...HEAD")
    ap.add_argument("--range", nargs=2, metavar=("FROM", "TO"), default=None,
                    help="guard: compare two commits instead (CI: HEAD^1 HEAD on the PR merge ref)")
    ap.add_argument("--head-ref", default=os.environ.get("GITHUB_HEAD_REF", ""),
                    help="the PR's head branch (default $GITHUB_HEAD_REF)")


def main(args: argparse.Namespace) -> int:
    repo = Path(args.repo).resolve()
    if args.action == "list":
        for p in main_only_files(repo):
            print(f"main-only  {p}")
        for p in SPANS:
            if (repo / p).is_file():
                print(f"span       {p}")
        return 0
    if args.action == "regen":
        return regen(repo)
    changed = changed_files(repo, base=args.base, rng=tuple(args.range) if args.range else None)
    ok, bad = guard(repo, changed, args.head_ref)
    if ok:
        why = f" (exempt head branch {args.head_ref})" if exempt(args.head_ref) else ""
        print(f"ok: this change edits no main-only generated file{why}")
        return 0
    for p in bad:
        msg = f"{p} is generated on main only — a pull request must not edit it"
        if os.environ.get("GITHUB_ACTIONS") == "true":
            print(f"::error file={p}::{msg}")
        else:
            print(f"ERROR: {msg}")
    print(FIX.format(files=" ".join(bad)))
    return 1
